{
    unsigned char h[crypto_hash_sha256_BYTES];

    crypto_hash_sha256(h, in, (unsigned long long) inlen);
    sodium_bin2hex(hex, 2 * crypto_hash_sha256_BYTES + 1, h, sizeof h);
}

